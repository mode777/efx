/* interleaved quad/billboard vertex: pos(3f) uv(2f) color(ub4n) = 24 bytes.
 * z is the already-divided NDC depth: 0 for 2D quads (the `quad` pipeline
 * ignores it), a real perspective depth for billboards/particles (the
 * `billboard` pipeline depth-tests it). */
typedef struct {
    float x, y, z;
    float u, v;
    uint8_t r, g, b, a;
} pipe_vertex;

/* interleaved mesh vertex: pos(3f) normal(3f) uv(2f) color(4f) = 48 bytes
 * (design D1: all attribute slots present, defaults filled at upload).
 * The full 4-element layout matches the shader input signature exactly;
 * D3D11 CreateInputLayout returns E_INVALIDARG for partial coverage. */
typedef struct {
    float x, y, z;
    float nx, ny, nz;
    float u, v;
    float r, g, b, a;
} pipe_mesh_vertex;

typedef struct {
    sg_image img;
    sg_view view;
    int wrap, filter; /* F6b per-texture sampler state */
    int mipmaps;      /* F6e: image carries a generated mip chain */
} pipe_tex;

/* F5a offscreen render target: env-default color+depth attachments plus a
 * texture view over the color image (sampling a target = texture coercion,
 * design D1) */
typedef struct {
    int w, h;
    sg_image color, depth;
    sg_view color_att, depth_att, color_tex;
} pipe_rt;

typedef struct {
    sg_buffer vbuf, ibuf;
    sg_buffer posed_vbuf; /* F7: dynamic posed vertex buffer (skinned only) */
    int has_posed;
    uint32_t posed_rev;   /* last uploaded pose revision */
    int index_count; /* 0 = non-indexed (draw vertex count) */
    int vertex_count;
} pipe_mesh_surface;

typedef struct {
    int surface_count;
    pipe_mesh_surface *surfaces;
} pipe_mesh;

typedef struct {
    sg_shader quad_shd;
    sg_pipeline quad_pip[3];
    sg_pipeline bill_pip[3]; /* F11: same shader/layout, depth test/no write */
    sg_shader mesh_shd;
    sg_pipeline mesh_pip[3];
    sg_pipeline mesh_pip_cw[3]; /* GL-family RT passes: projection y-flip
                                   mirrors winding (F5a) */
    /* F5b post passes: one shader + pipeline per pass type (uniform-driven,
       no permutations) */
    sg_shader post_shd[6];
    sg_pipeline post_pip[6];
    sg_sampler smp;
    sg_sampler smp_nearest; /* render-scale nearest blit */
    sg_sampler tex_smp[3][2][2]; /* F6b/F6e per-texture samplers, cached by
                                    (wrap, filter, mipmaps) */
    sg_view white_view; /* engine white texture, used for absent F4b maps */
    sg_buffer vbuf;
    size_t vbuf_size;       /* bytes; grown on demand (dynamic quad batch) */
    sg_buffer post_vbuf;    /* static fullscreen quad for post passes */
    pipe_vertex *scratch;
    int scratch_cap;
    int *run_first, *run_verts; /* per-run first vertex / vertex count */
    int run_cap;
    int *rec_boff;  /* F11: per-record first vertex (billboard/particles) */
    int *rec_bcnt;  /* F11: per-record vertex count */
    int rec_cap;
    int installed;
    int depth_remap; /* D3D11/Metal: fold 0..1 depth range into MVP */
    int rt_flip;     /* GL-family: flip y when rendering into RTs (F5a) */
    sg_attachments default_atts; /* invalid id = swapchain (capture only) */
    /* view-projection cache: consecutive mesh records usually share the
       camera snapshot, so recompose only when it (or the aspect) changes */
    int pv_valid;
    efx_camera3d pv_cam;
    float pv_aspect;
    int pv_flip;
    float pv[16];
} pipe_state;

